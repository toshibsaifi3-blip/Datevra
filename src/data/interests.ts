export const ALL_INTEREST_OPTIONS: readonly string[] = INTEREST_CATEGORIES.flatMap(
  (cat) => cat.items,
);

export const INTEREST_CATEGORY_BY_ITEM: ReadonlyMap<string, string> = new Map(
  INTEREST_CATEGORIES.flatMap((cat) =>
    cat.items.map((item) => [item.toLowerCase(), cat.label] as const),
  ),
);

export function searchInterestOptions(query: string, categoryId?: string): string[] {
  const q = query.trim().toLowerCase();
  const source =
    categoryId && categoryId !== "all"
      ? INTEREST_CATEGORIES.find((c) => c.id === categoryId)?.items ?? []
      : ALL_INTEREST_OPTIONS;
  if (!q) return [...source];
  return source.filter((item) => item.toLowerCase().includes(q));
}
